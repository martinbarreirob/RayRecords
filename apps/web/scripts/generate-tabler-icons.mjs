// Writes `src/app/core/ui/tabler-icons.generated.ts`: the path data of the Tabler icons the app
// draws, so only those ship in the bundle (no icon font, no runtime requests).
//
// The set is every icon a stock category can use (`CATEGORY_ICONS` in `@rayrecords/shared`) plus
// the interface icons listed below. Run it after changing either list:
//
//   pnpm --filter @rayrecords/web icons:tabler
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Interface icons, on top of the ones categories can pick. */
const UI_ICONS = [
  'adjustments-horizontal',
  'alert-circle',
  'arrow-down',
  'arrow-left',
  'arrow-right',
  'arrow-up',
  'calendar',
  'check',
  'chevron-down',
  'chevron-left',
  'chevron-right',
  'chevron-up',
  'chevrons-left',
  'copy',
  'device-desktop',
  'dots',
  'external-link',
  'eye',
  'eye-off',
  'file',
  'grip-vertical',
  'help-circle',
  'layout-grid',
  'list',
  'loader-2',
  'lock',
  'lock-open',
  'logout',
  'minus',
  'moon',
  'pencil',
  'plus',
  'search',
  'shopping-cart',
  'sun',
  'trash',
  'upload',
  'user',
  'x',
];

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const outline = join(dirname(require.resolve('@tabler/icons/package.json')), 'icons', 'outline');
const { version } = require('@tabler/icons/package.json');

const constants = readFileSync(join(here, '../../../packages/shared/src/category-look.ts'), 'utf8');
const list = /export const CATEGORY_ICONS = \[([\s\S]*?)\] as const;/.exec(constants);
if (!list) throw new Error('CATEGORY_ICONS not found in category-look.ts');
const stockIcons = [...list[1].matchAll(/'([^']+)'/g)].map((match) => match[1]);

const names = [...new Set([...stockIcons, ...UI_ICONS])].sort();
const entries = names.map((name) => {
  let svg;
  try {
    svg = readFileSync(join(outline, `${name}.svg`), 'utf8');
  } catch {
    throw new Error(`Tabler has no outline icon called "${name}"`);
  }
  const shapes = [...svg.matchAll(/<(\w+)\b([^>]*)\/>/g)].filter(
    ([, , attributes]) => !attributes.includes('stroke="none"'),
  );
  // Outline icons are drawn with paths only; anything else would need the component to change.
  const paths = shapes.map(([, tag, attributes]) => {
    const d = /\bd="([^"]+)"/.exec(attributes);
    if (tag !== 'path' || !d) throw new Error(`"${name}" has a <${tag}> the app cannot draw`);
    return d[1];
  });
  return `  '${name}': [\n${paths.map((d) => `    '${d}',`).join('\n')}\n  ],`;
});

const file = `// Generated by scripts/generate-tabler-icons.mjs from @tabler/icons ${version} (MIT). Do not edit.

/** Path data (\`d\`) of each icon, drawn on a 24 × 24 grid with a round stroke and no fill. */
export const TABLER_ICONS = {
${entries.join('\n')}
} as const satisfies Record<string, readonly string[]>;

export type IconName = keyof typeof TABLER_ICONS;
`;

writeFileSync(join(here, '../src/app/core/ui/tabler-icons.generated.ts'), file);
console.log(`${names.length} icons written (${stockIcons.length} for categories).`);
