/** Icons whose name contains the text, ignoring accents and case; all of them for no text. */
export function searchIcons(query: string): CategoryIcon[] {
  const needle = normalizeText(query);
  if (needle === '') return [...CATEGORY_ICONS];
  return CATEGORY_ICONS.filter((icon) => normalizeText(ICON_LABELS[icon]).includes(needle));
}
